import { test, expect } from '@playwright/test'

// 설치면 판정·필터·천장/바닥 편집 모드 — OE-EQP-03·04·05, OE-UI-10, OE-OBJ-08
test('surface: h_c unknown → 미정, set h_c, assign ceiling, filter, ceiling mode locks', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.locator('.floor-card').first().getByRole('button', { name: /→/ }).click()
  await page.getByRole('button', { name: '설비 편집' }).click()
  await page.getByRole('button', { name: '설비', exact: true }).click()
  const rows = page.locator('.object-list button')
  const total = await rows.count()
  // h_c 를 모르면 천장 판정은 미정이고 0 으로 채우지 않는다(AC2)
  await expect(page.getByTestId('sf-unknown')).toContainText(String(total))
  await expect(page.getByTestId('sf-ceiling')).toContainText('0')
  // 천장 모드에 들어가도 h_c 를 모르면 놓지 못한다
  await page.getByTestId('mode-ceiling').click()
  await expect(page.locator('.notice.toast')).toContainText('천장고')
  await page.getByRole('button', { name: '＋ 설비 배치' }).click()
  await page.getByRole('button', { name: /배치 시작/ }).click()
  await expect(page.locator('.notice.toast')).toContainText('천장고')
  await page.getByTestId('mode-floor').click()
  // h_c 입력 후에도 FCU(z=1.2m)는 미정 — 설치면을 사람이 정한다(OE-EQP-05)
  await page.getByLabel('천장 높이(m)').fill('2.7'); await page.getByLabel('천장 높이(m)').press('Enter')
  await rows.first().click()
  await expect(page.getByTestId('surface-row')).toContainText('미정')
  await page.getByLabel('설치면 지정').selectOption('ceiling')
  await expect(page.getByTestId('surface-row')).toContainText('천장')
  await expect(page.getByTestId('sf-ceiling')).toContainText('1')
  // 필터: 천장만 → 1개
  await page.getByTestId('sf-ceiling').click()
  await expect(rows).toHaveCount(1)
  await page.getByTestId('sf-all').click()
  // 바닥·벽 쪽에서는 천장 설비를 고쳐지지 않는다(AC1)
  await rows.first().click()
  await page.getByRole('button', { name: '속성 적용' }).click()
  await expect(page.locator('.notice.toast')).toContainText('천장 편집 모드')
  // 천장 모드: 천장 설비만 편집, z 는 구역 안에서만(Q10)
  await page.getByTestId('mode-ceiling').click()
  await rows.first().click()
  await page.getByLabel('Z 좌표').fill('1.5')
  await page.getByRole('button', { name: '속성 적용' }).click()
  await expect(page.locator('.notice.toast')).toContainText('천장고')
  await page.getByLabel('Z 좌표').fill('2.9')
  await page.getByRole('button', { name: '속성 적용' }).click()
  await expect(page.locator('.notice.toast')).toContainText('수정')
  // 천장 설비가 아닌 설비는 천장 모드에서 못 고친다(AC3)
  await rows.nth(1).click()
  await page.getByRole('button', { name: '속성 적용' }).click()
  await expect(page.locator('.notice.toast')).toContainText('천장 설비만')
  await page.waitForTimeout(800)
  await page.screenshot({ path: '.local/proto-ceiling-mode.png', fullPage: true })
  expect(errors).toEqual([])
})
